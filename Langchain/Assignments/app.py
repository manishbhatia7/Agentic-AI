import streamlit as st
from backend import pydantic_chain,parser,final_chain,ai_conversation_chain
st.set_page_config(page_title="Feedback Analysis Software",page_icon="📚",layout="wide")
st.title('Feedback Analysis Software')
st.write('Please enter a detailed review about your favorite gadget')
topic=st.text_area("Please enter your detailed review to be analysed by AI")
mode=st.selectbox("Choose the Mode",["Mode1-Analyze Feedback","Mode2-Generate Customer Reply","Mode3-Chat with AI"])
if mode =="Mode1-Analyze Feedback":
    if st.button("Submit",key="explain_submit"):
        if not topic.strip():
            st.warning("Please enter the topic")
        else:
            with st.spinner("Your review is getting analysed by AI..."):
                response=pydantic_chain.invoke({'feedback':topic,'format_instructions':parser.get_format_instructions()})
            st.subheader("Feedback Analysis")
            st.write("Sentiment:",response.sentiment)
            st.write("Summary:",response.summary)
            st.write("Pros:")
            for pro in response.pros:
                st.markdown("- {}".format(pro))
            st.write("Cons:")
            for con in response.cons:
                st.markdown("- {}".format(con))
            st.write("Key Themes:")
            for theme in response.key_themes:
                st.markdown("- {}".format(theme))
        
elif mode =="Mode2-Generate Customer Reply":
    if st.button("Submit",key='generate_reply'):
        if not topic.strip():
            st.warning("Please enter Customer Feedback")
        else:
            with st.spinner("Your reply is being Generated by AI..."):
                response=final_chain.invoke({'feedback':topic,'format_instructions':parser.get_format_instructions()})
            st.subheader("Customer Feedback Analysis")
            st.write(response['feedback'])
            st.write(response['analysis'].sentiment)
            st.write(response['analysis'].summary)
            st.write("Pros")
            for pro in response['analysis'].pros:
                st.markdown("- {}".format(pro))
            st.write("Cons")
            for con in response['analysis'].cons:
                 st.markdown("- {}".format(con))
            st.write("Key Themes")
            for theme in response['analysis'].key_themes:
                st.markdown("- {}".format(theme))       
            st.subheader("AI Generated Customer Reply")            
            st.write(response['reply'])
elif mode=='Mode3-Chat with AI':
    # Step 1: Initialize conversation history
    if "messages" not in st.session_state:
        st.session_state["messages"] = []

    # Step 2: Display previous messages
    for message in st.session_state["messages"]:
        with st.chat_message(message["role"]):
            st.write(message["content"])

    # Step 3: Accept a new user message
    user_input = st.chat_input("Please type your message")

    if user_input:

        # Step 4: Save the user's message
        st.session_state["messages"].append(
            {"role": "user", "content": user_input}
        )
     # Step 5: Display the user's message
        with st.chat_message("user"):
            st.write(user_input)

        # Step 6: Generate an AI response
        with st.spinner("AI is thinking..."):
            ai_response = ai_conversation_chain.invoke({
                "messages": st.session_state["messages"][:-1],
                "question": user_input
            })

        # Step 7: Display the AI response
        with st.chat_message("assistant"):
            st.write(ai_response)

        # Step 8: Save the AI response
        st.session_state["messages"].append(
            {"role": "assistant", "content": ai_response}
        )    
            
    
                
        
        
                
            
                    
  
